/*
 * Projectile Motion Summary
 * -------------------------
 * Horizontal velocity (vx) = v0 * cos(theta) [Constant]
 * Vertical velocity (vy)   = v0 * sin(theta) - g*t
 *
 * Key Formulas:
 * - Time of Flight (T)   = (2 * v0 * sin(theta)) / g
 * - Max Height (H)       = (v0^2 * sin^2(theta)) / (2 * g)
 * - Horizontal Range (R) = (v0^2 * sin(2 * theta)) / g
 *
 * Complementary Angles Property:
 * -----------------------------
 * Two angles theta1 and theta2 result in the same range R
 * if they are complementary (theta1 + theta2 = 90 degrees).
 */